// Re-grade the recorded 2026-11-13 mainnet campaign with stricter rules
// (red-team T5-3). Reads the committed step files only; signs nothing.
//
// 1. An LLM round where the model never attempted a payment is
//    "not_attempted", not a pass: the wallet was not tested.
// 2. A recorded-only step whose text states a value is checked against
//    the data it recorded.
// 3. Everything else that was recorded without an assertion stays
//    "recorded" and is not counted as a test.
//
// Usage: node scripts/mainnet/regrade.mjs [steps-dir] [--write <file.md>]

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_STEPS = join(HERE, "..", "..", "docs", "demo", "mainnet-campaign", "2026-11-13", "steps");

/** Claims stated in the text of recorded-only steps, as predicates on their data. */
export const CLAIMS = {
  w48_spent_after_ghost: {
    claim: "the failed transfer left the window at 2,000,000",
    check: (data) => data && data.spent_in_window === "2000000",
  },
  w53_window_kept: {
    claim: "restore kept the day's spend at 2,000,000",
    check: (data) => data && data.spent_in_window === "2000000",
  },
  w64_remaining_zero: {
    claim: "remaining reads 0, not a negative or wrapped number",
    // The owner had lowered the daily cap below the day's spend; the
    // claim is that remaining clamps to 0 instead of going negative.
    check: (data) => data && data.remaining === "0",
  },
  r07_new_wallet_keys: {
    claim: "the redeployed wallet has 0 access keys",
    check: (data) => data && data.keys === 0,
  },
  r18_spent_while_held: {
    claim: "the window includes the held amount and stays under the daily cap",
    check: (data) => data && BigInt(data.spent_in_window) + BigInt(data.remaining) === BigInt(data.daily_max),
  },
  r20_spent_after_reject: {
    claim: "after the rejection the window still adds up to the daily cap",
    check: (data) => data && BigInt(data.spent_in_window) + BigInt(data.remaining) === BigInt(data.daily_max),
  },
};

function attemptedPayment(step) {
  // Only a model round (a step with a model and its response) can fail to
  // attempt a payment; owner setup steps in the LLM phases are ordinary.
  if (!step.model || !step.response) return true;
  if (step.actual === "model did not call pay") return false;
  const calls = (step.response && step.response.tool_calls) || [];
  return calls.some((call) => {
    try {
      const args = JSON.parse(call.arguments || "{}");
      return call.name === "pay" && typeof args.receiver_id === "string";
    } catch {
      return false;
    }
  });
}

/** Grade one recorded step. */
export function regradeStep(step) {
  if (step.pass === null || step.pass === undefined) {
    const claim = CLAIMS[step.id];
    if (!claim) return { id: step.id, verdict: "recorded" };
    let ok = false;
    try {
      ok = Boolean(claim.check(step.data));
    } catch {
      ok = false;
    }
    return { id: step.id, verdict: ok ? "claim_pass" : "claim_fail", claim: claim.claim };
  }
  if (!attemptedPayment(step)) return { id: step.id, verdict: "not_attempted" };
  return { id: step.id, verdict: step.pass ? "pass" : "fail" };
}

export function regrade(steps) {
  const rows = steps.map(regradeStep);
  const count = (verdict) => rows.filter((row) => row.verdict === verdict).length;
  return {
    rows,
    totals: {
      steps: rows.length,
      pass: count("pass"),
      fail: count("fail"),
      not_attempted: count("not_attempted"),
      claim_pass: count("claim_pass"),
      claim_fail: count("claim_fail"),
      recorded: count("recorded"),
    },
  };
}

export function loadSteps(dir = DEFAULT_STEPS) {
  return readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .sort()
    .map((name) => JSON.parse(readFileSync(join(dir, name), "utf8")));
}

function markdown({ rows, totals }) {
  const lines = [
    "# Mainnet campaign 2026-11-13, re-graded",
    "",
    "Generated by `node scripts/mainnet/regrade.mjs` from the committed step files. It signs nothing.",
    "",
    "The original report counted 170 passes. With the stricter rules below:",
    "",
    "| Verdict | Steps | Meaning |",
    "|---|---|---|",
    `| pass | ${totals.pass} | an on-chain assertion held |`,
    `| fail | ${totals.fail} | an on-chain assertion did not hold |`,
    `| not_attempted | ${totals.not_attempted} | an LLM round where the model never tried to pay, so the wallet was not tested |`,
    `| claim_pass | ${totals.claim_pass} | a recorded-only step whose stated value matches its recorded data |`,
    `| claim_fail | ${totals.claim_fail} | a recorded-only step whose stated value does not match |`,
    `| recorded | ${totals.recorded} | a snapshot with no stated value, not a test |`,
    "",
    "Not attempted:",
    "",
    ...rows.filter((row) => row.verdict === "not_attempted").map((row) => `- \`${row.id}\``),
    "",
    "Checked claims:",
    "",
    ...rows.filter((row) => row.claim).map((row) => `- \`${row.id}\`: ${row.claim} (${row.verdict})`),
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  const writeAt = args.indexOf("--write");
  const out = writeAt >= 0 ? args[writeAt + 1] : null;
  const dir = args.find((arg, index) => !arg.startsWith("--") && index !== writeAt + 1) || DEFAULT_STEPS;
  const result = regrade(loadSteps(dir));
  console.log(JSON.stringify(result.totals, null, 2));
  if (out) writeFileSync(out, markdown(result), "utf8");
}
