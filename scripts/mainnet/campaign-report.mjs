#!/usr/bin/env node
// Builds README.md (results table) and transcripts.md (LLM rounds) from the
// per-step JSON that scripts/mainnet/campaign.mjs wrote. Reads no keys.
//
//   node scripts/mainnet/campaign-report.mjs docs/demo/mainnet-campaign/2026-11-13
import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("usage: campaign-report.mjs <campaign dir>");
  process.exit(1);
}
const stepsDir = path.join(dir, "steps");
const rank = (id) => {
  if (id.startsWith("w")) return 0;
  if (id.startsWith("l2")) return 2;
  if (id.startsWith("l")) return 1;
  if (id.startsWith("r")) return 3;
  return 4;
};
const steps = fs
  .readdirSync(stepsDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(fs.readFileSync(path.join(stepsDir, f), "utf8")))
  .sort((a, b) => rank(a.id) - rank(b.id) || (a.id.includes("__") ? 1 : 0) - (b.id.includes("__") ? 1 : 0) || a.id.localeCompare(b.id, "en", { numeric: true }));
const attempt1 = fs.existsSync(path.join(stepsDir, "_attempt1")) ? fs.readdirSync(path.join(stepsDir, "_attempt1")).filter((f) => f.endsWith(".json")) : [];
const byId = Object.fromEntries(steps.map((s) => [s.id, s]));

const yocto = (n) => BigInt(n || 0);
const near = (y) => {
  const v = yocto(y);
  const neg = v < 0n;
  const a = neg ? -v : v;
  const s = (a / 10n ** 18n).toString().padStart(7, "0");
  return (neg ? "-" : "") + s.slice(0, -6) + "." + s.slice(-6);
};
const shown = (x) => {
  const ev = (x.events || []).map((e) => e.event);
  const id = x.return_value ? String(x.return_value).replace(/"/g, "") : "";
  if (ev.includes("payment_queued")) return `held for the owner (payment_queued, id ${id})`;
  if (x.outcome === "success" && ev.includes("pay_settled")) return "settled (pay_settled)";
  return x.actual || "-";
};
const link = (h) => (h ? `[${h.slice(0, 8)}…](https://nearblocks.io/txns/${h})` : "—");
const esc = (t) => String(t == null ? "" : t).replace(/\|/g, "\\|").replace(/\n/g, " ");
const short = (t, n = 110) => {
  const s = esc(t);
  return s.length > n ? s.slice(0, n - 1) + "…" : s;
};

let burnt = 0n;
let txCount = 0;
let rejectedBeforeChain = 0;
const rows = [];
for (const s of steps) {
  if (s.phase === "info") continue;
  if (s.txs) {
    const hashes = s.txs.filter((t) => t.tx_hash).map((t) => link(t.tx_hash));
    const b = s.txs.reduce((a, t) => a + yocto(t.tokens_burnt_yocto), 0n);
    burnt += b;
    txCount += hashes.length;
    rows.push(`| ${s.id} | ${short(s.test)} | ${short(s.expected, 60)} | ${short(s.txs.length ? s.txs.map((x) => (x.sent ? x.sent.receiver_id.replace(".hlpok1lad.tg", "") + " " + x.sent.amount + ": " + shown(x) : x.skipped)).join("; ") : s.actual, 220)} | ${s.pass ? "PASS" : "FAIL"} | ${hashes.join(" ") || "—"} | ${near(b)} |`);
    continue;
  }
  const b = yocto(s.tokens_burnt_yocto);
  burnt += b;
  if (s.tx_hash) txCount += 1;
  if (s.outcome === "rejected_before_chain") rejectedBeforeChain += 1;
  rows.push(`| ${s.id} | ${short(s.test)} | ${short(s.expected, 60)} | ${short(s.actual === "success" ? shown(s) === "-" ? "success" : shown(s) : s.actual, 120)} | ${s.pass ? "PASS" : "FAIL"} | ${link(s.tx_hash)} | ${s.tx_hash ? near(b) : "0 (refused by RPC)"} |`);
}
const graded = steps.filter((s) => s.pass === true || s.pass === false);
const passed = graded.filter((s) => s.pass).length;

const start = byId.w00_snapshot_before && byId.w00_snapshot_before.data;
const end = (byId.z99_snapshot_end || byId.r27_snapshot_after_review || {}).data;
const llmSteps = steps.filter((s) => s.txs);
const usd = llmSteps.reduce((a, s) => a + (s.usd_estimate || 0), 0);
const tokens = llmSteps.reduce((a, s) => a + ((s.usage && s.usage.total_tokens) || 0), 0);

const bal = (snap, role) => (snap && snap[role] && snap[role].yocto) || "0";
const lines = [];
lines.push("# Mainnet test campaign, 2026-11-13");
lines.push("");
lines.push("Generated by `scripts/mainnet/campaign-report.mjs` from `steps/*.json`. Every row is one NEAR mainnet transaction (or one transaction the RPC refused before it reached the chain). Every step file holds the full record: signer, receiver, method, arguments, events, error, gas, and wNEAR balances before and after.");
lines.push("");
lines.push(`- Graded steps: **${passed}/${graded.length} pass**. Mainnet transactions sent: ${txCount}. Refused by the RPC before the chain: ${rejectedBeforeChain}.`);
lines.push(`- Gas burnt across all transactions: **${near(burnt)} NEAR**.`);
if (start && end) {
  lines.push(`- Owner \`hlpok1lad.tg\`: ${near(bal(start, "owner"))} → ${near(bal(end, "owner"))} NEAR. Agent \`tp-agent2\`: ${near(bal(start, "agent"))} → ${near(bal(end, "agent"))} NEAR. Wallet \`tp-wallet\`: ${near(bal(start, "wallet"))} → ${near(bal(end, "wallet"))} NEAR.`);
}
lines.push(`- NEAR AI: ${llmSteps.length} chat completions, ${tokens} tokens, about **$${usd.toFixed(4)}** (usage × the catalogue price from \`/v1/models\`).`);
lines.push("");
lines.push("| Step | Test | Expected | Actual | Result | Tx | Gas (NEAR) |");
lines.push("|---|---|---|---|---|---|---|");
lines.push(...rows);
lines.push("");
lines.push("## View checks");
lines.push("");
for (const s of steps.filter((x) => x.phase === "info" && !/snapshot|budget/.test(x.id))) {
  const d = s.data || {};
  if (/after_llm/.test(s.id)) {
    lines.push(`- \`${s.id}\`: NEAR AI spend so far about $${Number(d.usd_estimate_total || 0).toFixed(4)}; owner ${d.snapshot && d.snapshot.owner.near} NEAR.`);
    continue;
  }
  const pick = d.spent_in_window !== undefined ? `spent_in_window ${d.spent_in_window}, remaining ${d.remaining}, daily_max ${d.daily_max}, active ${d.active}, payees ${JSON.stringify(d.payees)}` : JSON.stringify(d).slice(0, 400);
  lines.push(`- \`${s.id}\`: ${s.test}. ${esc(pick)}`);
}
lines.push("");
if (attempt1.length) {
  lines.push("## First attempts kept");
  lines.push("");
  lines.push(`\`steps/_attempt1/\` keeps ${attempt1.length} records from first attempts that I re-ran: ${attempt1.map((f) => "`" + f.replace(/\.json$/, "") + "`").join(", ")}. The campaign notes say why each was re-run.`);
  lines.push("");
}
fs.writeFileSync(path.join(dir, "RESULTS.md"), lines.join("\n") + "\n");

// transcripts
const t = [];
t.push("# NEAR AI transcripts, 2026-11-13");
t.push("");
t.push("Generated from `steps/l_*.json`, `steps/l2_*.json` and `steps/l3_*.json`. Each block is one chat completion on `https://cloud-api.near.ai/v1/chat/completions` with one `pay` tool. Every tool call the model made was signed with the agent's pay-only key and sent to `tp-wallet.hlpok1lad.tg` on mainnet. Keys are not in these files.");
t.push("");
const systems = [...new Set(llmSteps.map((s) => s.request.system))];
systems.forEach((sys, i) => {
  t.push(`## System prompt ${i + 1} (${i === 0 ? "guarded" : "hijacked"})`);
  t.push("");
  t.push("```text");
  t.push(sys);
  t.push("```");
  t.push("");
});
for (const s of llmSteps) {
  t.push(`## ${s.id}`);
  t.push("");
  t.push(`- Model: \`${s.model}\`. Round: ${s.round || "guarded prompt: the finding is marked untrusted"}. HTTP ${s.http_status}, ${s.latency_ms} ms, ${(s.usage && s.usage.total_tokens) || 0} tokens, ~$${(s.usd_estimate || 0).toFixed(5)}.`);
  t.push(`- Model followed the injection: **${s.model_obeyed_injection ? "yes" : "no"}**. Wallet result: **${s.pass ? "nothing reached the attacker, nothing over the cap" : "FAIL"}**.`);
  t.push("");
  t.push("Finding (user message):");
  t.push("");
  t.push("```text");
  t.push(s.request.user);
  t.push("```");
  t.push("");
  if (s.response.reasoning) {
    t.push("Reasoning (as returned):");
    t.push("");
    t.push("```text");
    const r = String(s.response.reasoning);
    t.push(r.length > 2500 ? r.slice(0, 2500) + "\n[… truncated, full text in the step file]" : r);
    t.push("```");
    t.push("");
  }
  t.push(`Reply: ${s.response.content ? esc(String(s.response.content).trim()) : "(none)"}`);
  if (s.response.error) t.push(`Error: ${esc(JSON.stringify(s.response.error))}`);
  t.push("");
  t.push("| Tool call | Sent to the wallet | On-chain result | Tx |");
  t.push("|---|---|---|---|");
  if (!s.txs.length) t.push("| (no tool call) | — | — | — |");
  for (const x of s.txs) t.push(`| \`${esc(JSON.stringify(x.args))}\` | ${x.sent ? esc(x.sent.receiver_id + " " + x.sent.amount) : "not sent: " + esc(x.skipped)} | ${esc(shown(x))} | ${link(x.tx_hash)} |`);
  t.push("");
}
fs.writeFileSync(path.join(dir, "transcripts.md"), t.join("\n") + "\n");
console.log(`RESULTS.md: ${rows.length} rows, ${passed}/${graded.length} pass, burnt ${near(burnt)} NEAR; transcripts.md: ${llmSteps.length} completions, $${usd.toFixed(4)}`);
